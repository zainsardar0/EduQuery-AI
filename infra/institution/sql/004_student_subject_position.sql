SET NOCOUNT ON;
SET XACT_ABORT ON;

IF OBJECT_ID(N'dbo.EDUQUERY_STUDENT_SUBJECT_RESULT_SOURCE', N'V') IS NULL
    THROW 51020, 'The database owner must supply dbo.EDUQUERY_STUDENT_SUBJECT_RESULT_SOURCE.', 1;

DECLARE @RequiredColumns table (ColumnName sysname NOT NULL PRIMARY KEY);
INSERT @RequiredColumns VALUES
    (N'CAMPUS'), (N'STUDENT_REFERENCE'), (N'ROLL_NUMBER'), (N'STUDENT_NAME'), (N'FATHER_NAME'),
    (N'CLASS_LEVEL'), (N'SECTION'), (N'SCHOOL_YEAR'), (N'SUBJECT'), (N'OBTAINED_MARKS'),
    (N'TOTAL_MARKS'), (N'PERCENTAGE'), (N'RESULT_STATUS');

IF EXISTS (
    SELECT 1 FROM @RequiredColumns AS required
    WHERE NOT EXISTS (
        SELECT 1
        FROM sys.columns AS c
        WHERE c.object_id = OBJECT_ID(N'dbo.EDUQUERY_STUDENT_SUBJECT_RESULT_SOURCE')
          AND UPPER(c.name) = required.ColumnName
    )
)
    THROW 51021, 'The certified student subject source does not satisfy the required column contract.', 1;

EXEC(N'
CREATE OR ALTER VIEW eduquery_reporting.STUDENT_SUBJECT_POSITION_V1 AS
SELECT
    CAMPUS, STUDENT_REFERENCE, ROLL_NUMBER, STUDENT_NAME, FATHER_NAME,
    CLASS_LEVEL, SECTION, SCHOOL_YEAR, SUBJECT, OBTAINED_MARKS, TOTAL_MARKS,
    PERCENTAGE, RESULT_STATUS,
    DENSE_RANK() OVER (
        PARTITION BY CAMPUS, SCHOOL_YEAR, CLASS_LEVEL, UPPER(LTRIM(RTRIM(SUBJECT)))
        ORDER BY PERCENTAGE DESC
    ) AS POSITION_IN_SCHOOL,
    DENSE_RANK() OVER (
        PARTITION BY CAMPUS, SCHOOL_YEAR, CLASS_LEVEL, SECTION, UPPER(LTRIM(RTRIM(SUBJECT)))
        ORDER BY PERCENTAGE DESC
    ) AS POSITION_IN_SECTION
FROM dbo.EDUQUERY_STUDENT_SUBJECT_RESULT_SOURCE
WHERE PERCENTAGE IS NOT NULL
  AND NULLIF(LTRIM(RTRIM(SUBJECT)), '''') IS NOT NULL
  AND UPPER(LTRIM(RTRIM(SUBJECT))) <> ''TOTAL'';
');
